package org.jpstale.common.service.item;

/**
 * **每一级锻造要投的 12 格石头**（原版 `AgingLevelSheltom[20][12]`，ex-machina
 * `src/game/Legacy/Game/Interface/sinTrade.cpp`，逐字抄）。
 *
 * <p><b>语义</b>（2026-09-22/23 厘清）：每行的 12 个数是**该格放哪一档石头**，
 * {@code 0} = 空格；不是"要几颗"。索引 = **当前锻造等级**（0 = 从 +0 往 +1 投）。
 * 这与用户说的"NPC 界面 3×4 一共 12 格"完全对上（用户 2026-09-22）。
 *
 * <p>数值规律（可自检）：起始档位随等级抬升，且**奇数级只填 11 格、偶数级填满 12 格**
 * （所以 +0 投 5 颗、+1 投 6 颗…），档位号即 `sinOS1 | (tier &lt;&lt; 8)` 里的 tier。
 *
 * <p>⚠ 这是**原版源码里的表**，不是我们编的；但它是 ex-machina（8 职业时代）那一支的数，
 * 与 EU 数据是否一致**未核**（我们的 `agelist` 只有掷点列，没有宝石列）。若日后发现 EU 的
 * 投石配方不同，以 EU 为准并在这里替换。
 */
public final class AgingMaterial {

    private AgingMaterial() {
    }

    /** 12 格（= 原版界面 3×4）；0 表示该格空着 */
    public static final int SLOTS = 12;

    /** 20 级（索引 = 当前等级；+0 ⇒ 0，+19 ⇒ 19） */
    private static final int[][] SLOTS_BY_LEVEL = {
            {3, 3, 4, 4, 5, 0, 0, 0, 0, 0, 0, 0},
            {3, 3, 4, 4, 5, 5, 0, 0, 0, 0, 0, 0},
            {3, 3, 4, 4, 5, 5, 6, 0, 0, 0, 0, 0},
            {3, 3, 4, 4, 5, 5, 6, 6, 0, 0, 0, 0},
            {3, 3, 4, 4, 5, 5, 6, 6, 7, 0, 0, 0},
            {3, 3, 4, 4, 5, 5, 6, 6, 7, 7, 0, 0},
            {3, 3, 4, 4, 5, 5, 6, 6, 7, 7, 8, 0},
            {3, 3, 4, 4, 5, 5, 6, 6, 7, 7, 8, 8},
            {4, 4, 5, 5, 6, 6, 7, 7, 8, 8, 9, 0},
            {4, 4, 5, 5, 6, 6, 7, 7, 8, 8, 9, 9},
            {5, 5, 6, 6, 7, 7, 8, 8, 9, 9, 10, 0},
            {5, 5, 6, 6, 7, 7, 8, 8, 9, 9, 10, 10},
            {6, 6, 7, 7, 8, 8, 9, 9, 10, 10, 11, 0},
            {6, 6, 7, 7, 8, 8, 9, 9, 10, 10, 11, 11},
            {7, 7, 8, 8, 9, 9, 10, 10, 11, 11, 12, 0},
            {7, 7, 8, 8, 9, 9, 10, 10, 11, 11, 12, 12},
            {8, 8, 9, 9, 10, 10, 11, 11, 12, 12, 13, 0},
            {8, 8, 9, 9, 10, 10, 11, 11, 12, 12, 13, 13},
            {9, 9, 10, 10, 11, 11, 12, 12, 13, 13, 14, 0},
            {9, 9, 10, 10, 11, 11, 12, 12, 13, 13, 14, 14},
    };

    /**
     * 该等级要投的 12 格档位（下标 = 格号，值 = 档位 1..14；0 = 空格）。
     * 等级超出表长（≥20）时返回**空表**（= 不投，不兜底）。
     */
    public static int[] slotsAt(int level) {
        if (level < 0 || level >= SLOTS_BY_LEVEL.length) {
            return new int[SLOTS];
        }
        return SLOTS_BY_LEVEL[level].clone();
    }

    /** 该等级实际要投几颗（非 0 的格数）。 */
    public static int countAt(int level) {
        int n = 0;
        for (int t : slotsAt(level)) {
            if (t != 0) {
                n++;
            }
        }
        return n;
    }

    /** 表覆盖的等级数（20）。 */
    public static int levels() {
        return SLOTS_BY_LEVEL.length;
    }
}
